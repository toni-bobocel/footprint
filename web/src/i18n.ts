export const STRINGS: Record<Lang, Strings> = { en, fr, es, pt, de, it, zh, ja, ar, ru }

export function detect(): Lang {
  const saved = localStorage.getItem('footprint.lang')
  if (saved && (LANGS as readonly string[]).includes(saved)) return saved as Lang
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase()
    if ((LANGS as readonly string[]).includes(code)) return code as Lang
  }
  return 'en'
}
